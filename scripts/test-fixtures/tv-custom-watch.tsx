// Render the TV branch in isolation; mobile controls must never mount here.
import { mock } from 'bun:test';
import assert from 'node:assert/strict';
import React, { act } from 'react';
import { createRoot } from 'react-dom/client';
import { JSDOM } from 'jsdom';

const dom = new JSDOM('<div id="root"></div>', { url: 'https://tatakai.me/' });
Object.defineProperties(globalThis, { window: { value: dom.window, configurable: true }, document: { value: dom.window.document, configurable: true }, navigator: { value: dom.window.navigator, configurable: true }, IS_REACT_ACT_ENVIRONMENT: { value: true, configurable: true } });
const navigation: string[] = [], saves: unknown[][] = [];
let nativeProps: any, viewProps: any;
const episodes = [{ id: 'dubbindo_episode:5', label: 'Upload Five', number: 5 }, { id: 'dubbindo_episode:6', label: 'Upload Six', number: 6 }];
const streams = [{ url: 'https://media.test/480.mp4', source: 'Dubbing Indonesia', quality: '480p', sourceType: 'mp4', headers: { Referer: 'https://dubbindo.site/' } }, { url: 'https://media.test/720.mp4', source: 'Dubbing Indonesia', quality: '720p', sourceType: 'mp4', headers: { Referer: 'https://dubbindo.site/' } }];
const empty = () => null;
const wrapper = ({ children }: any) => <>{children}</>;
mock.module('react-i18next', () => ({ useTranslation: () => ({ t: (key: string) => key }) }));
mock.module('react-router-dom', () => ({ useNavigate: () => (url: string) => navigation.push(url), useParams: () => ({ namespace: 'stremio-local', sourceId: 'series', id: 'dubbindo_show', episodeId: episodes[0].id }) }));
mock.module('@tanstack/react-query', () => ({ useQuery: () => ({ data: 'local-download-key' }) }));
mock.module('../../src/core/tv/device', () => ({ isTV: () => true }));
mock.module('../../src/hooks/ui/useUiTranslation', () => ({ useUiTranslation() {} }));
mock.module('../../src/hooks/ui/useIsNativeApp', () => ({ useIsMobileApp: () => true, useIsDesktopApp: () => false }));
mock.module('../../src/hooks/ui/use-mobile', () => ({ useIsMobile: () => false }));
mock.module('../../src/lib/uiI18n', () => ({ default: { t: (key: string) => key } }));
mock.module('../../src/lib/utils', () => ({ cn: (...values: unknown[]) => values.filter(Boolean).join(' ') }));
mock.module('../../src/lib/languageUtils', () => ({ normalizeWatchLanguageKey: () => 'und' }));
mock.module('../../src/hooks/api/useCustomSource', () => ({ useCustomSource: () => ({ source: { name: 'Dubbing Indonesia', kind: 'watch' } }), useCustomInfo: () => ({ data: { title: 'Selected Upload', entries: episodes } }), useCustomWatch: () => ({ data: { sources: streams }, refetch() {}, isLoading: false, isError: false, isFetching: false }) }));
mock.module('../../src/hooks/media/useExtensionLibrary', () => ({ useExtensionTitleProgress: () => ({ ready: true, row: {}, initialPosition: 12, save: (...args: unknown[]) => saves.push(args), profile: 'guest' }) }));
mock.module('../../src/hooks/media/useCustomCatalog', () => ({ useCustomCatalog: () => ({}) }));
mock.module('../../src/hooks/media/useCustomTracker', () => ({ useCustomTracker: () => ({}) }));
mock.module('../../src/core/extensions/compatibility/downloads', () => ({ extensionVideoKey: async () => 'local-download-key' }));
mock.module('../../src/components/video/NativeTorrentPlayer', () => ({ NativeTorrentPlayer: (props: any) => { nativeProps = props; return <div data-native-url={props.url} />; } }));
mock.module('../../src/components/video/MobileVideoPlayer', () => ({ MobileVideoPlayer: () => { throw Error('Touch player mounted on Android TV'); } }));
mock.module('../../src/components/video/VideoPlayer', () => ({ VideoPlayer: () => { throw Error('Web player mounted on Android TV'); } }));
mock.module('../../src/components/video/EmbedPlayer', () => ({ EmbedPlayer: empty }));
mock.module('../../src/pages/tv/TVWatchView', () => ({ TVWatchView: (props: any) => { viewProps = props; return <>{props.player}<button data-tv-source-picker onClick={() => navigation.push('source-picker')} /><button data-tv-episode-picker onClick={() => navigation.push('episode-picker')} /></>; } }));
mock.module('../../src/components/layout/Background', () => ({ Background: empty }));
mock.module('../../src/components/layout/Sidebar', () => ({ Sidebar: empty }));
mock.module('../../src/components/layout/MobileNav', () => ({ MobileNav: empty }));
mock.module('../../src/components/watch/SourceLanguageTabs', () => ({ SourceLanguageTabs: empty }));
mock.module('../../src/components/extensions/SourceDebug', () => ({ SourceDebug: empty }));
mock.module('../../src/components/extensions/CustomCatalogPanel', () => ({ CustomCatalogComments: empty }));
mock.module('../../src/components/ui/tooltip', () => ({ Tooltip: wrapper, TooltipContent: wrapper, TooltipProvider: wrapper, TooltipTrigger: wrapper }));
mock.module('../../src/components/ui/GlassPanel', () => ({ GlassPanel: wrapper }));
mock.module('../../src/components/ui/alert', () => ({ Alert: wrapper, AlertDescription: wrapper }));
mock.module('../../src/components/ui/button', () => ({ Button: (props: any) => <button {...props} /> }));

const { default: CustomWatchPage } = await import('../../src/pages/custom/CustomWatchPage');
const root = createRoot(dom.window.document.getElementById('root')!);
await act(async () => root.render(<CustomWatchPage />));
assert.equal(nativeProps.url, streams[0].url);
assert.equal(nativeProps.episodeId, episodes[0].id);
assert.equal(nativeProps.headers.Referer, streams[0].headers.Referer);
assert.deepEqual(viewProps.episodes.map((episode: any) => episode.episodeId), episodes.map(episode => episode.id));
assert.equal(nativeProps.initialSeekSeconds, 12);
await act(async () => viewProps.onSource(1));
assert.equal(nativeProps.url, streams[1].url);
assert.equal(viewProps.sources[1].selected, true);
await act(async () => nativeProps.onSourceRequest(0));
assert.equal(nativeProps.url, streams[0].url);
await act(async () => nativeProps.onSourceRequest());
await act(async () => nativeProps.onQueueRequest());
assert.deepEqual(navigation.splice(0), ['source-picker', 'episode-picker']);
nativeProps.onProgressUpdate(30, 120);
assert.deepEqual(saves, [[30, 120]]);
viewProps.onEpisode(episodes[1].id);
assert.equal(navigation.pop(), '/x/stremio-local/series/watch/dubbindo_show/dubbindo_episode%3A6');
nativeProps.onBack();
assert.equal(navigation.pop(), '/x/stremio-local/series/info/dubbindo_show');
await act(async () => root.unmount());
dom.window.close();
console.log('TV custom watch: native playback, quality selection, explicit IDs and progress passed');
